"""Write payments/webhooks_gen.py from spec/payments_webhooks.json.  Usage: python3 tools/gen_client.py"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "spec", "payments_webhooks.json")
OUT = os.path.join(ROOT, "payments", "webhooks_gen.py")

HEADER = '''# GENERATED by tools/gen_client.py from spec/payments_webhooks.json. Do not edit by hand:
# change the spec and run `make gen`.
import json
from urllib import request

from config import PAYMENTS_URL


def _call(method, path, payload=None):
    data = json.dumps(payload).encode() if payload is not None else None
    req = request.Request(PAYMENTS_URL + path, data=data, method=method,
                          headers={"Content-Type": "application/json"})
    with request.urlopen(req, timeout=TIMEOUT) as resp:
        return json.load(resp)
'''


def render(spec):
    out = [HEADER.replace("TIMEOUT", str(spec["timeout_s"]))]
    for op in spec["operations"]:
        params = re.findall(r"\{(\w+)\}", op["path"])
        path = repr(re.sub(r"\{\w+\}", "%s", op["path"]))
        if params:
            path += " % (" + ", ".join(params) + ",)"
        args = params + (["payload"] if op.get("body") else [])
        call = "_call(%r, %s%s)" % (op["method"], path, ", payload" if op.get("body") else "")
        out.append("\n\ndef %s(%s):\n    return %s\n" % (op["name"], ", ".join(args), call))
    return "".join(out)


def main():
    with open(SPEC) as fh:
        text = render(json.load(fh))
    with open(OUT, "w") as fh:
        fh.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
