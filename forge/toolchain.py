"""The third-party tools forge carries: config/toolchain.json declares them, mise installs them.

`npm install -g` and `pip install` write into the prefix of the node or python that was current at that
moment, and mise keeps every node and python in its own prefix, so the next `latest` had none of them
(twice: 14 packages gone the second time, GSD's `gsd-sdk` and `gsd-tools` dangling). mise's own `npm:` and
`pipx:` tools live in a per-package directory that holds no node or python version, and
`python.default_packages_file` is applied inside `mise install python@X`, so forge writes two files and asks
mise (docs/toolchain-design.md, with the measurements):

  ~/.config/mise/conf.d/forge.toml   the manifest's `tools`, one line each: mise reads conf.d, so forge owns
                                     one whole file and never merges into the user's config.toml
  ~/.default-python-packages         the manifest's `pip` list: libraries that scripts import under plain
                                     python3, installed by mise into each new python as it installs it

Both start with HEADER; a file that exists without it is somebody's own and is never overwritten. A tool is
looked up with `mise ls --json` (installed at the pin), a pip library with the current `python3`. `--fix`
installs only what is missing, at its pin, and never upgrades or downgrades one that is present.
"""
import json
import os
import re
import shutil
import subprocess

from forge import lib

# config/toolchain.json is user data (the engine's git ignores config/); examples/toolchain.json is the template.
MANIFEST = os.path.join(lib.ROOT, "config", "toolchain.json")
SECTIONS = ("tools", "pip")
TRACKS = ("latest", "frozen")  # what `forge update` does with an entry: follow upstream, or leave it (the why says why)
OPTION_KEY = re.compile(r"^[A-Za-z0-9_-]+$")
HEADER = "# GENERATED by forge toolchain from config/toolchain.json -- do not edit; `forge toolchain --fix` rewrites it.\n"
LIST_TIMEOUT, INSTALL_TIMEOUT = 120, 900


def entries():
    """({"tools": [...], "pip": [...]}, why not): config/toolchain.json's entries, each a dict with a name, an
    exact pinned version and a why, and optionally a `track` and, for a tool, `options` (extra keys of mise's
    inline table, e.g. the `url` of an `http:` tool). A file that cannot be read, a wrong shape or no entry at
    all is a reason, and the doc is then empty: a check that saw nothing is not a pass (non-negotiable 7)."""
    try:
        with open(MANIFEST, encoding="utf-8") as fh:
            doc = json.load(fh)
    except (OSError, ValueError) as e:
        return {}, "config/toolchain.json cannot be read: %s" % e
    if not isinstance(doc, dict):
        return {}, "config/toolchain.json is not an object with a \"tools\" and a \"pip\" list"
    # An unknown key is a misspelled section ("pips"), whose entries would go unchecked and let a missing
    # package pass, or the old "npm" section; "_"-prefixed keys are comments (the file's own `_doc`).
    unknown = sorted(k for k in doc if k not in SECTIONS + ("skills",) and not k.startswith("_"))  # skills: forge/skillpins.py's
    if unknown:
        return {}, "config/toolchain.json: unknown section %s, want only \"tools\" and \"pip\"" % ", ".join(
            "\"%s\"" % k for k in unknown)
    out = {}
    for kind in SECTIONS:
        items = doc.get(kind, [])
        if not isinstance(items, list):
            return {}, "config/toolchain.json: \"%s\" is not a list" % kind
        names = []
        for e in items:
            bad = _entry_error(e)
            if bad:
                return {}, "config/toolchain.json: a \"%s\" entry %s: %r" % (kind, bad, e)
            if e["name"] in names:
                return {}, "config/toolchain.json: \"%s\" lists %s twice" % (kind, e["name"])
            names.append(e["name"])
        out[kind] = items
    if not out["tools"] and not out["pip"]:
        return {}, "config/toolchain.json lists 0 entries, and a check that saw nothing is not a pass"
    return out, None


def _entry_error(e):
    """What is wrong with one manifest entry, or None."""
    if not isinstance(e, dict) or not all(isinstance(e.get(k), str) and e[k].strip() for k in ("name", "version", "why")):
        return "without a name, a pinned version and a why"
    if e["version"] == "latest":
        return "pinned to \"latest\" (the pin is an exact version; `track` says whether it follows upstream)"
    if e.get("track", "latest") not in TRACKS:
        return "with a track that is neither \"latest\" nor \"frozen\""
    opts = e.get("options", {})
    # mise reads conf.d in every directory, so a file it cannot parse breaks every mise command: what cannot be
    # written as TOML is refused here. `version` is written from the pin, and a value is a scalar or a list of them.
    if not isinstance(opts, dict) or not all(OPTION_KEY.match(k) and k != "version" and _scalar_or_list(v) for k, v in opts.items()):
        return "whose options are not an object of plain names (not \"version\") holding strings, numbers, booleans or lists of them"
    return None


def _scalar_or_list(v):
    return isinstance(v, (str, int, float, bool)) or (isinstance(v, list) and all(isinstance(x, (str, int, float, bool)) for x in v))


def render_mise(tools):
    """conf.d/forge.toml: HEADER, [tools], one `"name" = "version"` line per tool (an inline table with the
    entry's options when it has any), in the manifest's order."""
    lines = [HEADER, "[tools]\n"]
    for e in tools:
        opts = e.get("options")
        body = ("{ " + ", ".join(["version = " + json.dumps(e["version"])] + ["%s = %s" % (k, json.dumps(v)) for k, v in opts.items()]) + " }"
                if opts else json.dumps(e["version"]))
        lines.append("%s = %s\n" % (json.dumps(e["name"]), body))
    return "".join(lines)


def render_pips(pips):
    """The default-python-packages file: HEADER, then one `name==version` line per library."""
    return HEADER + "".join("%s==%s\n" % (e["name"], e["version"]) for e in pips)


def mise_file():
    """Where mise reads forge's tools from: <mise config dir>/conf.d/forge.toml."""
    base = os.environ.get("MISE_CONFIG_DIR") or os.path.join(os.environ.get("XDG_CONFIG_HOME") or os.path.join(lib.HOME, ".config"), "mise")
    return os.path.join(base, "conf.d", "forge.toml")


def pip_file():
    """Where mise reads the libraries to put into each new python (its python.default_packages_file)."""
    return os.environ.get("MISE_PYTHON_DEFAULT_PACKAGES_FILE") or os.path.join(lib.HOME, ".default-python-packages")


def file_state(path, text):
    """"current" (holds `text`), "missing", "unreadable" (a permission error, a directory), "stale" (forge's header
    over other content) or "foreign" (a file that does not start with HEADER, which is somebody's own and is left
    alone)."""
    try:
        with open(path, encoding="utf-8") as fh:
            have = fh.read()
    except FileNotFoundError:
        return "missing"
    except UnicodeDecodeError:
        return "foreign"
    except OSError:
        return "unreadable"
    return "current" if have == text else "stale" if have.startswith(HEADER) else "foreign"


def tool_run(argv, timeout, cwd=None):
    """(exit code, stdout, last three lines of stderr) of argv; a command that cannot run is (None, "", why). Three,
    because mise ends its errors with a line of noise and the reason is the one before."""
    try:
        r = subprocess.run(argv, capture_output=True, text=True, timeout=timeout, cwd=cwd)
    except (OSError, subprocess.TimeoutExpired) as e:
        return None, "", "%s: %s" % (type(e).__name__, e)
    return r.returncode, r.stdout, " | ".join(r.stderr.strip().splitlines()[-3:])


def pip_name(name):
    """PEP 503: how pip compares names (case, and - _ . alike)."""
    return re.sub(r"[-_.]+", "-", name).lower()


def mise_state():
    """({tool: [(installed version, whether mise resolves it)]}, why not): what `mise ls --json` says, asked from
    HOME so that "resolves" means the global config chain (config.toml and conf.d) and not a project's mise.toml."""
    if not shutil.which("mise"):
        return {}, "mise is not on PATH -- install it (https://mise.jdx.dev)"
    cmd = ["mise", "ls", "--json"]
    code, out, err = tool_run(cmd, LIST_TIMEOUT, cwd=lib.HOME)
    if code != 0:
        return {}, "`%s` failed (exit %s): %s" % (" ".join(cmd), code, err)
    try:
        return {name: [(v["version"], bool(v.get("active"))) for v in vs if v.get("installed")]
                for name, vs in json.loads(out).items()}, None
    except (ValueError, KeyError, TypeError, AttributeError) as e:
        return {}, "`%s` printed no JSON object of tools (%s: %s)" % (" ".join(cmd), type(e).__name__, e)


def pip_state():
    """({normalised name: version}, why not) of what the current `python3` has installed."""
    cmd = ["python3", "-m", "pip", "list", "--format=json", "--disable-pip-version-check"]
    code, out, err = tool_run(cmd, LIST_TIMEOUT)
    if code != 0:
        return {}, "`%s` failed (exit %s): %s" % (" ".join(cmd), code, err)
    try:
        return {pip_name(d["name"]): d["version"] for d in json.loads(out)}, None
    except (ValueError, KeyError, TypeError) as e:
        return {}, "`%s` printed no JSON list of packages (%s: %s)" % (" ".join(cmd), type(e).__name__, e)


def _gsd_pinned():
    """Whether GSD is on and patched, which is what makes a missing config/toolchain.json a FAIL: the patched,
    staged copy installs through its pinned package. An unpatched GSD (a stranger's, installed by forge init
    through pnpm dlx) pins nothing. A checkout with no config/forge.json has not been initialised, and says
    so on every other row; here it is off."""
    try:
        return lib.on("gsd") and lib.gsd_patched()
    except SystemExit:
        return False


def check():
    """(results, todo, where): one result per tool and pip library of config/toolchain.json and per generated
    file (PASS present at the pin, or current; WARN a pip library at another version, which nothing here
    changes; FAIL missing, installed only at another version, a stale, missing or foreign file, or its tool
    could not be asked), `todo` (what --fix can add: {"tools": [(name, pin)], "pip": [(name, pin)], "files":
    [(label, path, text)]}) and the mise and python3 that were asked. A list that cannot be read or is empty
    is one FAIL named `toolchain`."""
    todo = {"tools": [], "pip": [], "files": []}
    if not os.path.exists(MANIFEST) and not _gsd_pinned():
        return [lib.Result("SKIP", "toolchain", lib.NOT_ARMED + "no config/toolchain.json, so no third-party tool is pinned "
                           "(examples/toolchain.json is the template; a missing file is a FAIL "
                           "when GSD is on and gsd_patches is true)")], todo, ""
    doc, why = entries()
    if why:
        return [lib.Result("FAIL", "toolchain", why)], todo, ""
    have, mise_why = mise_state()
    pip_have, pip_why = pip_state()
    results = []
    for e in doc["tools"]:
        name, pin = e["name"], e["version"]
        if mise_why:
            results.append(lib.Result("FAIL", name, mise_why))
        elif pin in [v for v, _ in have.get(name, [])]:
            # Installed is not the same as used: another config (a `latest` in config.toml) can make mise
            # resolve a different version, and the pin is then not what runs.
            active = [v for v, on in have[name] if on and v != pin]
            results.append(lib.Result("WARN", name, "pin %s is installed, but mise resolves %s (another config requests it); left as it is"
                                      % (pin, ", ".join(active))) if active else lib.Result("PASS", name, pin))
        else:
            other = [v for v, _ in have.get(name, [])]
            results.append(lib.Result("FAIL", name, "pinned %s, installed only %s" % (pin, ", ".join(other)) if other
                                      else "missing, pinned %s" % pin))
            todo["tools"].append((name, pin))
    for e in doc["pip"]:
        name, pin = e["name"], e["version"]
        label, got = "pip:" + name, pip_have.get(pip_name(name))
        if pip_why:
            results.append(lib.Result("FAIL", label, pip_why))
        elif got is None:
            results.append(lib.Result("FAIL", label, "missing, pinned %s" % pin))
            todo["pip"].append((name, pin))
        elif got == pin:
            results.append(lib.Result("PASS", label, got))
        else:
            results.append(lib.Result("WARN", label, "present at %s, pinned %s; left as it is" % (got, pin)))
    for label, path, text in (("file:mise", mise_file(), render_mise(doc["tools"])),
                              ("file:pip", pip_file(), render_pips(doc["pip"]))):
        state = file_state(path, text)
        if state == "current":
            results.append(lib.Result("PASS", label, "%s current" % path))
        elif state == "unreadable":
            results.append(lib.Result("FAIL", label, "%s cannot be read, left alone" % path))
        elif state == "foreign":
            results.append(lib.Result("FAIL", label, "%s is not forge's (no GENERATED header), left alone: move what is in it "
                                      "into config/toolchain.json and delete it" % path))
        else:
            results.append(lib.Result("FAIL", label, "%s %s" % (path, "missing" if state == "missing" else "differs from config/toolchain.json")))
            todo["files"].append((label, path, text))
    return results, todo, "mise: %s; python3: %s" % (shutil.which("mise") or "(none)", shutil.which("python3") or "(none)")


def write_files(files):
    """The labels of the files written: each is made from its text, unless lib.may_write refuses (a worktree, a
    copy, a toy HOME that points outside itself), which is printed and leaves them. A file that cannot be written
    is a `!` line naming it, and the others are still written."""
    if not files:
        return []
    ok, why = lib.may_write()
    if not ok:
        print(why)
        return []
    wrote = []
    for label, path, text in files:
        try:
            lib.makedirs(os.path.dirname(path))
            lib.write_text(path, text)
            wrote.append(label)
        except OSError as e:
            print("! %s: %s" % (path, e))
    return wrote


def install(todo):
    """{entry label: what ran, and how it ended}: ONE `mise install name@pin ...` for every missing tool and ONE
    `pip install name==pin ...` for every missing library, so the resolver sees them together. Never --upgrade:
    nothing present is touched."""
    calls = []
    if todo["tools"]:
        calls.append((["mise", "install"] + ["%s@%s" % t for t in todo["tools"]], [n for n, _ in todo["tools"]]))
    if todo["pip"]:
        calls.append((["python3", "-m", "pip", "install", "--disable-pip-version-check"] + ["%s==%s" % p for p in todo["pip"]],
                      ["pip:" + n for n, _ in todo["pip"]]))
    ran = {}
    for argv, labels in calls:
        code, _, err = tool_run(argv, INSTALL_TIMEOUT)
        cmd = "`%s`" % " ".join(argv)
        ran.update({label: ("still missing after " + cmd if code == 0 else "%s failed (exit %s): %s" % (cmd, code, err))
                    for label in labels})
    return ran


def cmd(a):
    """forge toolchain [--fix]: the check, one line per entry; --fix writes the two files and installs what is
    missing, then checks again. The recheck is the verdict, not an installer's exit code: an install that exits 0
    into the wrong place is still a FAIL."""
    results, todo, where = check()
    if a.fix and (todo["tools"] or todo["pip"] or todo["files"]):
        wrote = write_files(todo["files"])
        ran = install(todo)
        results, _, where = check()
        results = [r._replace(detail="%s; %s" % (r.detail, ran[r.name])) if r.level == "FAIL" and r.name in ran else
                   r._replace(detail=r.detail + " (installed by --fix)") if r.name in ran else
                   r._replace(detail=r.detail + " (written by --fix)") if r.name in wrote else r for r in results]
    if where:
        print(where)
    return lib.report(results)


def row():
    """The `toolchain` row of forge doctor: check() without --fix, in one result that says how many it looked at.
    FAIL when something fails (or the list is empty); WARN when a pip library is present at another version,
    which nothing here changes; SKIP when there is no file and GSD is off; else PASS."""
    results, _, _ = check()
    if len(results) == 1 and results[0].name == "toolchain":
        return results[0]
    pips = sum(r.name.startswith("pip:") for r in results)
    files = sum(r.name.startswith("file:") for r in results)
    checked = "%d tool(s), %d pip package(s), %d file(s)" % (len(results) - pips - files, pips, files)
    failing = [r.name for r in results if r.level == "FAIL"]
    other = [r.name for r in results if r.level == "WARN"]
    if failing:
        return lib.Result("FAIL", "toolchain", "%d failing: %s (checked %s)%s" % (
            len(failing), ", ".join(failing), checked, "; also at another version: " + ", ".join(other) if other else ""))
    if other:
        return lib.Result("WARN", "toolchain", "%d present at another version, left as it is: %s (checked %s)"
                          % (len(other), ", ".join(other), checked))
    return lib.Result("PASS", "toolchain", "checked %s, all present at their pin" % checked)
