"""See and change a project's configuration without asking an agent: `forge list` (every project, one project) and
`forge config [NAME] [@PROFILE] --on TYPE:NAME --off TYPE:NAME ...`.

Seeing: card() builds the short card (every project) and the full one (one project) as a dict, forge/render.py draws it,
and `--json` prints the dict, so the two views say the same. `forge list @` and `forge list @NAME` are forge/profiles.py's.

Changing: plan() applies the flags to in-memory copies of the two files that can hold the answer and returns what would
change; commit() writes it. A flag is `(op, type, name)`, op `on` or `off`, type one of TYPES. The rule that matters: a
change is written in the layer that owns the data, never in a generated field. `skills_keep` of a project file is
generated by scripts/sync/sync_skill_keep.py from config/forge.json (skill_keep), so:

  a common skill (common_skills)       off -> skill_keep.common_opt_out[<project file>]       on -> taken out of it again
  a skill of the project's extras row  off -> removed from skill_keep.extras[<project file>]   on -> appended to it
  a skill of a project with no row     its own skills_keep, which nothing generates but the common layer's union
  a skill that arrives through a set   refused (exit 2) with the two commands that work: `--off set:NAME`, or that and
                                       `--on skill:X` for each other member
  a server and an option               the project file's own fields (`servers`, `ui`, `command_guard`, ...)
  with @PROFILE: `skill:` and `set:`   that profile's row, profiles.offered.<name>.skills of the project file

Nothing is written until every flag has been accepted (a Refusal leaves both files as they were); the write is one pass over
at most two files, undone from memory if the second fails; the files are compared with what the plan read just before it, so
a change made while the owner decided is refused, not written over. After it the command runs the generators that depend
on what changed (sync_skill_keep.py when forge.json did, then `forge sync NAME --apply`; a profile row is read when a
session starts, so it has none) and says which layer it touched and the command that undoes it (two, in order, when a set and one
of its skills went in the same call: Plan.undo). A change that would leave `skills_keep: []`, or switch on a server whose secret is
missing, is a Refusal.

The screen (`forge config [NAME] [@PROFILE]` with no flag, in a terminal): screen() builds the rows from a Plan that has applied
nothing, runs forge/selector.py, and turns the rows that were toggled into the flags that would have toggled them; cmd_config
then hands those flags to change(), the code path of the flags, so the screen decides nothing and every refusal is the flags'."""
import copy
import json
import os
import sys

from forge import lib, mcp, profiles, render, selector, suggest

TYPES = ("skill", "set", "server", "option")
ORDER = ("set", "skill", "server", "option")  # the order the flags are applied in: a set goes before the skills that were taken from it
OPTIONS = ("ui", "command_guard", "enableAllProjectMcpServers")
FORGE_REL = "config/forge.json"


class Refusal(Exception):
    """Something the owner asked that cannot be done as asked: exit 2, nothing written."""


class Failure(Exception):
    """Something that went wrong on forge's side or in the files' state: exit 1."""


def _say(text="", err=False):
    print(text, file=sys.stderr if err else sys.stdout)


# ---- reading ---------------------------------------------------------------------------------------------------------------

def project_named(name):
    """(name, project dict) of the registry's project `name`; Refusal naming the closest one, or why the file cannot be read."""
    skipped = []
    known = lib.projects(skipped)
    if name in known:
        return name, known[name]
    why = {f[:-len(".claude.json")]: w for f, w in skipped}.get(name)
    if why:
        raise Refusal("project '%s' cannot be read (%s)" % (name, why))
    raise Refusal(suggest.message("project", name, known))


def project_here():
    """(name, project dict) of the folder's project, or Refusal."""
    found = profiles.project_here(os.getcwd())
    if not found:
        raise Refusal("%s is not inside a project of forge's registry (a project file forge cannot read is left out of it); "
                      "name one: forge list" % os.getcwd())
    return found


def _skill_keep():
    return lib.settings().get("skill_keep") or {}


def installed_skills():
    """The global skills a project could keep: the folders of ~/.claude/skills (what sync_skill_keep.py calls installed)."""
    root = os.path.join(lib.HOME, ".claude", "skills")
    return {d for d in os.listdir(root) if os.path.isdir(os.path.join(root, d))} if os.path.isdir(root) else set()


def origins(name, prof, sk):
    """{skill: sorted layers it comes from} for each skill the project file keeps: `common`, `extras` (named in the row),
    `set:NAME` (through a set of the row), `project` (the file's own list, for a project with no row); `unsynced` when
    no layer explains it (the file is behind the tables: sync_skill_keep.py --apply)."""
    fn, extras, sets = name + ".claude.json", sk.get("extras") or {}, sk.get("sets") or {}
    labels = {}
    if fn in extras:
        for item in extras[fn]:
            for n in (sets.get(item[1:], []) if item.startswith("@") else [item]):
                labels.setdefault(n, set()).add("set:" + item[1:] if item.startswith("@") else "extras")
    else:
        for n in prof.get("skills_keep") or []:
            labels.setdefault(n, set()).add("project")
    if fn not in (sk.get("common_exclude") or []):
        opt = set((sk.get("common_opt_out") or {}).get(fn) or [])
        for n in sk.get("common_skills") or []:
            if n not in opt:
                labels.setdefault(n, set()).add("common")
    return {n: sorted(labels.get(n) or ["unsynced"]) for n in prof.get("skills_keep") or [] if n != "*"}


def card(name, prof, full=False):
    """The card of one project as a dict: the short one (name, path, frozen, servers, skills as a count, profiles, options) or,
    with `full`, the whole (skills as a list with `origins`, plugins, the sets of its row, what it opted out of)."""
    keep = prof.get("skills_keep")
    every = keep is None or "*" in keep
    given = prof.get("profiles")
    out = {"project": name, "path": prof.get("project_path", ""), "frozen": bool(prof.get("frozen")),
           "servers": list(prof.get("servers", []))}
    if not full:
        out["skills"] = "*" if every else len(keep)
    else:
        sk, fn = _skill_keep(), name + ".claude.json"
        out["skills"] = ["*"] if every else list(keep)
        if not every:
            out["origins"] = origins(name, prof, sk)
        plugins = prof.get("plugins_keep")
        out["plugins"] = ["*"] if plugins is None else list(plugins)
        out["sets"] = [i[1:] for i in (sk.get("extras") or {}).get(fn, []) if i.startswith("@")]
        out["opted_out"] = list((sk.get("common_opt_out") or {}).get(fn) or [])
    out["options"] = {k: prof.get(k) if isinstance(prof.get(k), bool) else None for k in OPTIONS}
    out["profiles"] = {"default": given["default"], "offered": list(given["offered"])} if isinstance(given, dict) else None
    return out


def cmd_list(a):
    """forge list | forge list NAME | forge list @ | forge list @NAME [--json] [--names] [--session ID]. `@` forms are
    profiles.cmd_list, untouched. Without an argument: a short card per project (or, --names, the names). With a project's
    name: its full card. Exit 0, or 2 for a project that does not exist, cannot be read, or a flag that does not go with it."""
    target = a.target
    if target is not None and target.startswith("@"):
        return profiles.cmd_list(a)
    if a.session:
        _say("forge list: --session is for forge list @", err=True)
        return 2
    skipped = []
    known = lib.projects(skipped)
    for fn, why in skipped:
        _say("forge list: %s cannot be read (%s); left out" % (fn, why), err=True)
    if target is None:
        if a.names:
            for n in known:
                _say(n)
            return 0
        cards = [card(n, p) for n, p in known.items()]
        if a.json:
            _say(json.dumps(cards, indent=2, ensure_ascii=False))
        else:
            _say("\n\n".join("\n".join(render.card_lines(c, render.color_on())) for c in cards))
        return 0
    if a.names:
        _say("forge list: --names is for forge list (the projects' names) and forge list @ (a project's profiles)", err=True)
        return 2
    if target not in known:
        why = {f[:-len(".claude.json")]: w for f, w in skipped}.get(target)
        _say("forge list: %s" % ("project '%s' cannot be read (%s)" % (target, why) if why else suggest.message("project", target, known)),
             err=True)
        return 2
    c = card(target, known[target], full=True)
    if a.json:
        _say(json.dumps(c, indent=2, ensure_ascii=False))
    else:
        _say("\n".join(render.card_lines(c, render.color_on()) + [
            "  edit       forge config %s --off skill:X --on server:Y --off option:ui  (add @PROFILE for a profile's row; forge config --help)" % target]))
    return 0


# ---- the flags -------------------------------------------------------------------------------------------------------------

def parse_flag(op, text):
    """`TYPE:NAME` as (op, type, name); Refusal saying the form when it is not one, or the closest type when it is a typo."""
    typ, sep, name = text.partition(":")
    if not sep or not typ or not name.strip():
        raise Refusal("--%s %r is not TYPE:NAME (the types are %s), for example --%s skill:grilling" % (op, text, ", ".join(TYPES), op))
    if typ not in TYPES:
        raise Refusal(suggest.message("type", typ, TYPES, " in --%s %s" % (op, text)))
    return op, typ, name


def command(project, profile, flags):
    """The command line of `flags`, a list of (op, type, name)."""
    return "forge config %s%s %s" % (project, " @" + profile if profile else "", " ".join("--%s %s:%s" % f for f in flags))


def put_set(row, item):
    """`item` (`@NAME`) into `row` after the sets already there (at the front when there are none), so that taking a set out and
    putting it back, with the skills that were beside it, leaves the row as it was."""
    at = max([i for i, x in enumerate(row) if x.startswith("@")], default=-1) + 1
    row.insert(at, item)


# ---- the plan --------------------------------------------------------------------------------------------------------------

def _load(path):
    """(text, document) of a file forge may edit; Failure when it is missing or not a JSON object."""
    try:
        text = lib.read_text(path)
    except lib.Unreadable as e:
        raise Failure("%s cannot be read (%s)" % (lib.short(path), e.reason))
    if text is None:
        raise Failure("%s does not exist" % lib.short(path))
    try:
        doc = json.loads(text)
    except ValueError as e:
        raise Failure("%s is not valid JSON (%s)" % (lib.short(path), e))
    if not isinstance(doc, dict):
        raise Failure("%s is not a JSON object" % lib.short(path))
    return text, doc


class Plan:
    """The flags applied to copies of config/forge.json and the project file: `items` is one record per flag (op, type, name,
    layer, changed), `forge` and `proj` the documents as they would be, `texts` what was read."""

    def __init__(self, name, profile):
        self.name, self.profile, self.fn = name, profile, name + ".claude.json"
        self.before = None
        self.paths = {"forge": lib.SETTINGS, "project": os.path.join(lib.PROJECTS, self.fn)}
        self.texts, self.docs = {}, {}
        for key, path in self.paths.items():
            self.texts[key], self.docs[key] = _load(path)
        self.start = copy.deepcopy(self.docs)
        self.forge, self.proj = self.docs["forge"], self.docs["project"]
        self.items = []
        self.expected = None

    # -- what the tables say
    def sk(self):
        return self.forge.get("skill_keep") or {}

    def table(self, key, default):
        """A table of skill_keep for writing: made when it is not there."""
        return self.forge.setdefault("skill_keep", {}).setdefault(key, default)

    def row(self):
        return (self.sk().get("extras") or {}).get(self.fn)

    def excluded(self):
        return self.fn in (self.sk().get("common_exclude") or [])

    def opted_out(self):
        return set((self.sk().get("common_opt_out") or {}).get(self.fn) or [])

    def kept(self):
        """The skills sync_skill_keep.py would leave in the project file's skills_keep given these tables and this file, or None
        for a project that keeps every global skill. Mirrors that script's layers (extras row, common union, opt-out) and the
        pruning of what is not installed. commit() compares it with what the script then writes."""
        sk, sets, common = self.sk(), self.sk().get("sets") or {}, self.sk().get("common_skills") or []
        own, row, opt, excluded = self.proj.get("skills_keep"), self.row(), self.opted_out(), self.excluded()
        if row is not None:
            names = [n for item in row for n in (sets.get(item[1:], []) if item.startswith("@") else [item])]
            if not excluded:
                names += [n for n in common if n not in opt]
        elif own is None or "*" in own:
            return None
        else:
            names = list(own)
        if not excluded:
            names = [n for n in names if n not in opt] + [n for n in common if n not in opt]
        return set(names) & installed_skills()

    def record(self, op, typ, name, layer="", changed=True, note=""):
        self.items.append({"op": op, "type": typ, "name": name, "layer": layer, "changed": changed, **({"note": note} if note else {})})

    def project_rel(self):
        return "config/projects/%s" % self.fn

    # -- the names that must exist
    def need(self, kind, name, options, where=""):
        if name not in options:
            raise Refusal(suggest.message(kind, name, options, where))

    def need_skill(self, name):
        self.need("skill", name, installed_skills(), " in %s" % lib.short(os.path.join(lib.HOME, ".claude", "skills")))

    def need_set(self, name):
        self.need("set", name, self.sk().get("sets") or {}, " in skill_keep.sets of %s" % FORGE_REL)

    def need_members_installed(self, set_name):
        missing = sorted(set(self.sk()["sets"][set_name]) - installed_skills())
        if missing:
            raise Refusal("set '%s' names skills that are not installed (%s): sync_skill_keep.py would stop on them" % (set_name, ", ".join(missing)))

    # -- project-level flags
    def set_off(self, name):
        self.need_set(name)
        row = self.row()
        if row and "@" + name in row:
            row[:] = [i for i in row if i != "@" + name]
            self.record("off", "set", name, "skill_keep.extras[%s] in %s" % (self.fn, FORGE_REL))
        else:
            self.record("off", "set", name, changed=False, note="not in this project's row")

    def set_on(self, name):
        self.need_set(name)
        row = self.row()
        if row is None:
            raise Refusal("project '%s' has no skill_keep.extras row in %s, so there is no row to add the set '%s' to" % (self.name, FORGE_REL, name))
        self.need_members_installed(name)
        if "@" + name in row:
            self.record("on", "set", name, changed=False, note="already in this project's row")
        else:
            put_set(row, "@" + name)
            self.record("on", "set", name, "skill_keep.extras[%s] in %s" % (self.fn, FORGE_REL))

    def via_set(self, name, prefix=None, row=None):
        """The Refusal for a skill that arrives through a set: why, and the two commands that work."""
        prefix = prefix or "forge config %s" % self.name
        row = self.row() if row is None else row
        sets = self.sk().get("sets") or {}
        carriers = [i[1:] for i in row or [] if i.startswith("@") and name in sets.get(i[1:], [])]
        if not carriers:
            raise Refusal("skill '%s' of project '%s' is still kept after the change and arrives through no layer this command can edit" % (name, self.name))
        others = [n for c in carriers for n in sets[c] if n != name]
        off = prefix + "".join(" --off set:%s" % c for c in carriers)
        text = ["skill '%s' of project '%s' arrives through the set%s %s, so it cannot be switched off alone. Two commands work:" % (
            name, self.name, "s" if len(carriers) > 1 else "", ", ".join("'%s'" % c for c in carriers)),
            "  %s" % off, "      (the whole set goes)"]
        if others:
            text += ["  %s" % (off + "".join(" --on skill:%s" % n for n in dict.fromkeys(others))), "      (the set goes, its other members stay)"]
        else:
            text.append("(the skill is the set's only member, so the first is the one that works)")
        raise Refusal("\n".join(text))

    def skill_off(self, name):
        kept = self.kept()
        if kept is None:
            raise Refusal("project '%s' keeps every global skill (it has no skills_keep list), so one cannot be switched off alone" % self.name)
        if name not in kept:
            self.need_skill(name)
            self.record("off", "skill", name, changed=False, note="already off")
            return
        row = self.row()
        if name in (self.sk().get("common_skills") or []) and not self.excluded():
            self.table("common_opt_out", {}).setdefault(self.fn, []).append(name)
            layer = "skill_keep.common_opt_out[%s] in %s" % (self.fn, FORGE_REL)
        elif row is not None:
            row[:] = [i for i in row if i != name]
            layer = "skill_keep.extras[%s] in %s" % (self.fn, FORGE_REL)
        else:
            self.proj["skills_keep"] = [n for n in self.proj["skills_keep"] if n != name]
            layer = "skills_keep in %s" % self.project_rel()
        if name in (self.kept() or ()):
            self.via_set(name)
        self.record("off", "skill", name, layer)

    def skill_on(self, name):
        self.need_skill(name)
        kept = self.kept()
        if kept is None or name in kept:
            self.record("on", "skill", name, changed=False, note="already kept")
            return
        layer = ""
        if name in self.opted_out():
            opt = self.table("common_opt_out", {})
            opt[self.fn] = [n for n in opt[self.fn] if n != name]
            if not opt[self.fn]:
                del opt[self.fn]
            layer = "skill_keep.common_opt_out[%s] in %s" % (self.fn, FORGE_REL)
        if name not in (self.kept() or ()):
            if self.row() is not None:
                self.row().append(name)
                layer = "skill_keep.extras[%s] in %s" % (self.fn, FORGE_REL)
            else:
                self.proj["skills_keep"] = list(self.proj.get("skills_keep") or []) + [name]
                layer = "skills_keep in %s" % self.project_rel()
        self.record("on", "skill", name, layer)

    def registry(self):
        doc = lib.read_json(os.path.join(lib.ROOT, "config", "mcp-registry.json"), quiet=True)
        servers = doc.get("servers") if isinstance(doc, dict) else None
        return servers if isinstance(servers, dict) else {}

    def server_off(self, name):
        listed = self.proj.get("servers", [])
        if name in listed:
            self.proj["servers"] = [s for s in listed if s != name]
            self.record("off", "server", name, "servers in %s" % self.project_rel())
        else:
            self.need("server", name, self.registry(), " in config/mcp-registry.json")
            self.record("off", "server", name, changed=False, note="not in this project's servers")

    def need_secrets(self, name):
        """Refusal when the registry entry of `name` names a secret that config/secrets.json lacks: the generator would stop on it
        at every sync of the project. The check is the generator's own (mcp.resolved_server); only names are read, never printed."""
        secrets = {k: v for k, v in lib.read_json(os.path.join(lib.ROOT, "config", "secrets.json"), quiet=True).items() if not k.startswith("_")}
        errors = []
        mcp.resolved_server(name, self.registry()[name], secrets, errors)
        if errors:
            raise Refusal("server '%s' cannot be switched on: %s. Every sync of project '%s' would stop on it. Put that secret in "
                          "config/secrets.json (it links to credentials/secrets.json; name it there, never in the registry), or give "
                          "the registry entry another one" % (name, "; ".join(errors), self.name))

    def server_on(self, name):
        self.need("server", name, self.registry(), " in config/mcp-registry.json")
        listed = self.proj.get("servers", [])
        if name in listed:
            self.record("on", "server", name, changed=False, note="already in this project's servers")
        else:
            self.need_secrets(name)
            self.proj["servers"] = list(listed) + [name]
            self.record("on", "server", name, "servers in %s" % self.project_rel())

    def option(self, op, name):
        self.need("option", name, OPTIONS)
        now = self.proj.get(name) is True
        if now == (op == "on"):
            self.record(op, "option", name, changed=False, note="already %s" % op)
        else:
            self.proj[name] = op == "on"
            self.record(op, "option", name, "%s in %s" % (name, self.project_rel()))

    # -- a profile's row
    def profile_row(self):
        return self.proj["profiles"]["offered"][self.profile]

    def resolved(self):
        try:
            return set(profiles.resolve(self.name, self.proj, self.profile)["skills_keep"])
        except profiles.ProfileError as e:
            raise Refusal(str(e))

    def profile_where(self):
        return "profiles.offered.%s.skills in %s" % (self.profile, self.project_rel())

    def profile_set_off(self, name):
        self.need_set(name)
        skills = self.profile_row().get("skills", [])
        if "@" + name in skills:
            self.profile_row()["skills"] = [i for i in skills if i != "@" + name]
            self.record("off", "set", name, self.profile_where())
        elif "@" + name in profiles.definition(self.profile)["skills"]:
            raise Refusal("the set '%s' of profile '%s' comes from its definition, config/profile-defs/%s.json, which every project shares" % (name, self.profile, self.profile))
        else:
            self.record("off", "set", name, changed=False, note="not in this profile's row")

    def profile_set_on(self, name):
        self.need_set(name)
        self.need_members_installed(name)
        row, skills = self.profile_row(), self.profile_row().get("skills", [])
        if "@" + name in skills or "@" + name in profiles.definition(self.profile)["skills"]:
            self.record("on", "set", name, changed=False, note="already in this profile")
        else:
            row["skills"] = list(skills)
            put_set(row["skills"], "@" + name)
            self.record("on", "set", name, self.profile_where())

    def profile_skill_off(self, name):
        if name not in self.resolved():
            self.need_skill(name)
            self.record("off", "skill", name, changed=False, note="already off in this profile")
            return
        row = self.profile_row()
        row["skills"] = [i for i in row.get("skills", []) if i != name]
        if name in self.resolved():
            sets = self.sk().get("sets") or {}
            if any(i.startswith("@") and name in sets.get(i[1:], []) for i in row.get("skills", [])):
                self.via_set(name, "forge config %s @%s" % (self.name, self.profile), row.get("skills", []))
            d = profiles.definition(self.profile)["skills"]
            if name in d or any(i.startswith("@") and name in sets.get(i[1:], []) for i in d):
                raise Refusal("skill '%s' arrives through the definition of profile '%s', config/profile-defs/%s.json, which every project shares; "
                              "edit that file to change it for all of them" % (name, self.profile, self.profile))
            raise Refusal("skill '%s' arrives through the common layer every profile starts from; switch it off for the whole project: "
                          "forge config %s --off skill:%s" % (name, self.name, name))
        self.record("off", "skill", name, self.profile_where())

    def profile_skill_on(self, name):
        self.need_skill(name)
        if name in self.resolved():
            self.record("on", "skill", name, changed=False, note="already in this profile")
            return
        row = self.profile_row()
        row["skills"] = list(row.get("skills", [])) + [name]
        self.record("on", "skill", name, self.profile_where())

    # -- all of it
    def apply(self, changes):
        """Every flag, offs before ons (so `--off set:S --on skill:A` keeps A whatever the order on the line), sets before skills.
        Refusal for a flag given both ways, a name that does not exist, a flag that cannot be done."""
        both = sorted({(t, n) for o, t, n in changes if o == "on"} & {(t, n) for o, t, n in changes if o == "off"})
        if both:
            raise Refusal("%s:%s is given both --on and --off" % both[0])
        if self.proj.get("frozen"):
            raise Refusal("project '%s' is frozen: forge writes nothing for it, so a change here would do nothing" % self.name)
        if self.profile:
            bad = [t for _, t, _ in changes if t not in ("skill", "set")]
            if bad:
                raise Refusal("%s is not a thing a profile has: a profile row holds skills and sets; servers and options belong to the "
                              "project (forge config %s ...)" % (bad[0], self.name))
        self.before = None if self.profile else self.kept()
        todo = {"off": {"set": self.profile_set_off if self.profile else self.set_off,
                        "skill": self.profile_skill_off if self.profile else self.skill_off,
                        "server": self.server_off, "option": lambda n: self.option("off", n)},
                "on": {"set": self.profile_set_on if self.profile else self.set_on,
                       "skill": self.profile_skill_on if self.profile else self.skill_on,
                       "server": self.server_on, "option": lambda n: self.option("on", n)}}
        for op in ("off", "on"):
            for typ in ORDER:
                for o, t, n in changes:
                    if o == op and t == typ:
                        todo[op][typ](n)
        self.verify(changes)

    def verify(self, changes):
        """What was asked holds in what the tables now give, and the project file is still a valid one."""
        if self.profile:
            if self.items_changed():
                resolved = self.resolved()
                for o, t, n in changes:
                    if t == "skill" and (n in resolved) != (o == "on"):
                        raise Refusal("skill '%s' of profile '%s' is %s after the change although it was asked %s" % (
                            n, self.profile, "kept" if n in resolved else "not kept", o))
        else:
            kept = self.kept()
            if self.before and kept is not None and not kept:  # sync_skill_keep.py calls `skills_keep: []` an accident
                raise Refusal("project '%s' would be left with no skill at all (skills_keep: [] switches every global skill off). Keep "
                              "at least one, or take the skills_keep key out of %s to keep every global skill" % (self.name, self.project_rel()))
            for o, t, n in changes:
                if t == "skill" and kept is not None and (n in kept) != (o == "on"):
                    raise Refusal("skill '%s' of project '%s' is %s after the change although it was asked %s" % (
                        n, self.name, "kept" if n in kept else "not kept", o))
        why = lib.project_error(self.proj)
        if why:
            raise Refusal("the project file would no longer be valid: %s" % why)

    def forward(self):
        """The flags that did something, in the order they were applied."""
        return [(i["op"], i["type"], i["name"]) for i in self.items if i["changed"]]

    def undo(self):
        """The commands that put everything back, in the order to run them: every changed flag turned round, in one command. Where
        that cannot hold, `--on set:S` beside `--off skill:X` with X a member of S (the set brings X back, so the skill cannot stay
        off), the set goes in a second command that runs after the first."""
        turned = [("on" if o == "off" else "off", t, n) for o, t, n in self.forward()]
        sets = self.sk().get("sets") or {}
        skills_off = {n for o, t, n in turned if o == "off" and t == "skill"}
        late = [f for f in turned if f[:2] == ("on", "set") and skills_off & set(sets.get(f[2], []))]
        first = [f for f in turned if f not in late]
        return [command(self.name, self.profile, group) for group in (first, late) if group]

    def items_changed(self):
        return any(i["changed"] for i in self.items)

    def changed_files(self):
        """The keys of the files whose document differs from what was read: `forge` first, then `project`."""
        return [k for k in ("forge", "project") if self.docs[k] != self.start[k]]


def plan(name, profile, changes):
    """The Plan of `changes` ((op, type, name) tuples) on project `name` (and its profile `profile`, or None). Refusal when
    something cannot be done as asked; nothing is written either way."""
    p = Plan(name, profile)
    p.apply(changes)
    p.expected = None if profile else p.kept()  # what the project file's skills_keep must hold once sync_skill_keep.py has run
    return p


# ---- writing ---------------------------------------------------------------------------------------------------------------

def _run_tail(r):
    text = (r.stdout or "") + (r.stderr or "")
    return " | ".join(l.strip() for l in text.strip().splitlines()[-3:]) or "no output"


def commit(p, undo):
    """Write what `p` changed and run the generators that depend on it. Returns {"written": [paths], "sync": {step: exit code}}.
    Failure (exit 1) when a file is not what the plan read or is not in the form forge writes (nothing
    written), when the second file cannot be written (the first is put back), or when a generator fails after the write
    (the change stands; `undo` is the command that reverses it). change() has asked may_write() before it comes here."""
    keys = p.changed_files()
    for k in keys:  # the form forge writes: a file in another form would be rewritten whole, not just where it changed
        if lib.dumps(p.start[k]) + "\n" != p.texts[k]:
            raise Failure("%s is not in the form forge writes it (two-space JSON, one final newline), so a change would reformat all of "
                          "it: put it in that form first" % lib.short(p.paths[k]))
    result = {"written": [], "sync": {}}
    forge_changed = "forge" in keys
    try:
        with lib.lock():
            _write(p, keys, forge_changed, undo, result)
    except TimeoutError as e:
        raise Failure(str(e))
    if not p.profile:  # a profile row is read when a session starts: nothing is generated from it
        r = lib.run(["bin/forge", "sync", p.name, "--apply"], capture=True)
        result["sync"]["agent config"] = r.returncode
        if r.returncode:
            raise Failure("written, but forge sync %s --apply exits %d (%s); undo with: %s" % (p.name, r.returncode, _run_tail(r), undo))
    return result


def _write(p, keys, forge_changed, undo, result):
    """The writes of commit(), under the sync lock."""
    for k in keys:
        try:
            now = lib.read_text(p.paths[k])
        except lib.Unreadable as e:
            raise Failure("%s cannot be read now (%s); nothing was written" % (lib.short(p.paths[k]), e.reason))
        if now != p.texts[k]:
            raise Failure("%s changed while the plan was made; nothing was written. Run the command again" % lib.short(p.paths[k]))
    if forge_changed:  # the script rewrites every project whose file drifts from the tables: only on tables that are in step
        r = lib.run(["scripts/sync/sync_skill_keep.py", "--check"], capture=True)
        if r.returncode:
            raise Failure("sync_skill_keep.py --check exits %d (forge doctor's `skill keep` row) before this change, so applying it would "
                          "also rewrite other projects; nothing was written. Run `python3 scripts/sync/sync_skill_keep.py --apply` "
                          "first (%s)" % (r.returncode, _run_tail(r)))
    done = []
    try:
        for k in keys:
            lib.write_text(p.paths[k], lib.dumps(p.docs[k]) + "\n", mode="keep")
            done.append(k)
    except Exception as e:
        for k in done:
            lib.write_text(p.paths[k], p.texts[k], mode="keep")
        raise Failure("could not write %s (%s); %s" % (lib.short(p.paths[keys[len(done)]]), e,
                                                       "the earlier file was put back" if done else "nothing was changed"))
    result["written"] = [lib.short(p.paths[k]) for k in keys]
    lib.journal([("wrote", p.paths[k]) for k in keys], "config", "forge config")
    if forge_changed:
        r = lib.run(["scripts/sync/sync_skill_keep.py", "--apply"], capture=True)
        result["sync"]["skill keep"] = r.returncode
        if r.returncode:
            raise Failure("written, but sync_skill_keep.py --apply exits %d (%s); undo with: %s" % (r.returncode, _run_tail(r), undo))
        got = (lib.read_json(p.paths["project"], quiet=True) or {}).get("skills_keep")
        if p.expected is not None and (not isinstance(got, list) or set(got) != p.expected):
            raise Failure("written, but sync_skill_keep.py left skills_keep as %s, not the %s this change should give; undo with: %s" % (
                got, sorted(p.expected), undo))


def _ask(prompt):
    """True on a `y` or `yes` typed in the terminal; anything else, an empty line and the input ending included, is no."""
    sys.stderr.write(prompt)
    sys.stderr.flush()
    try:
        answer = sys.stdin.readline()
    except (OSError, ValueError):
        return False
    return answer.strip().lower() in ("y", "yes")


def has_terminal():
    return sys.stdin.isatty() and sys.stdout.isatty()


def change(name, profile, changes, yes=False, as_json=False):
    """The core of `forge config`: apply `changes` (a list of (op, type, name)) to project `name` (profile `profile` or None) and
    print what happened. In a terminal it asks [y/N] unless `yes`; without one it is a dry-run unless `yes`. Returns the exit
    code: 0 done, dry-run or nothing to change; 2 a Refusal (nothing written); 1 a Failure."""
    try:
        p = plan(name, profile, changes)
        changed = [i for i in p.items if i["changed"]]
        undo = p.undo() if changed else []
        doc = {"project": name, "profile": profile, "changes": p.items, "command": command(name, profile, p.forward()) if changed else None,
               "undo": undo or None, "applied": False, "written": [], "sync": {}}
        out = (lambda text="": _say(text, err=as_json))
        if not changed:
            out("forge config %s: nothing to change (%s)" % (name, "; ".join("%s:%s %s" % (i["type"], i["name"], i["note"]) for i in p.items)))
        else:
            out("forge config %s%s: %d change(s)" % (name, " @" + profile if profile else "", len(changed)))
            for i in p.items:
                out("  %-3s %-28s %s" % (i["op"], "%s:%s" % (i["type"], i["name"]), i["layer"] if i["changed"] else "no change (%s)" % i["note"]))
            out("command: %s" % doc["command"])
            for k, cmd in enumerate(undo):
                out("%s    %s" % ("undo:" if k == 0 else "then:", cmd))
            go = yes
            if yes or has_terminal():  # asked before the question, so a `y` is never answered with a refusal
                ok, why = lib.may_write()
                if not ok:
                    raise Failure(why)
            if not go and has_terminal():
                go = _ask("write these changes? [y/N] ")
            elif not go:
                out("dry-run: nothing written; add --apply (or --yes) to write")
            if go:
                res = commit(p, " && ".join(undo))
                doc.update(applied=True, written=res["written"], sync=res["sync"])
                out("written: %s" % ", ".join(res["written"]))
                if res["sync"]:
                    out("synced: %s" % ", ".join(res["sync"]))
            elif has_terminal():
                out("nothing written")
        if as_json:
            _say(json.dumps(doc, indent=2, ensure_ascii=False))
        return 0
    except (Refusal, profiles.ProfileError) as e:  # a profile that cannot be resolved is the owner's data, not a bug
        _say("forge config: %s" % e, err=True)
        return 2
    except Failure as e:
        _say("forge config: %s" % e, err=True)
        return 1

# ---- the screen ------------------------------------------------------------------------------------------------------------

NEW_PROFILE_ROW = "profile:+new"  # not a profile name: a name is kebab-case
CANCELLED = "forge config: cancelled, nothing was written"
NO_CHOICE = "forge config: nothing was changed, nothing was written"


def _skill_rows(p, on, groups, label):
    """The skill rows: one group per set of `groups` (the sets that bring skills here), then every other installed skill. A row
    is `skill:NAME`, on when `on` (None: every skill is) holds it; a skill in two groups is in the first only."""
    sets, have, seen, out = p.sk().get("sets") or {}, installed_skills(), set(), []
    for g in groups:
        members = [n for n in sets.get(g, []) if n in have and n not in seen]
        seen.update(members)
        if members:
            out.append(("skills from set %s" % g, [("skill:" + n, label(n), on is None or n in on) for n in members]))
    rest = sorted(have - seen)
    out.append(("skills" if not out else "other skills", [("skill:" + n, label(n), on is None or n in on) for n in rest]))
    return out


def sections(name, profile):
    """The screen's rows as selector sections for project `name` (or its profile `profile`). Refusal/Failure/ProfileError when the
    state cannot be read; nothing is applied, and nothing here decides what a toggle may do (change() does)."""
    p = Plan(name, profile)
    sets = sorted(p.sk().get("sets") or {})
    if profile:
        carried = [i[1:] for i in p.profile_row().get("skills", []) + profiles.definition(profile)["skills"] if i.startswith("@")]
        out = _skill_rows(p, p.resolved(), carried, lambda n: n)
        out.append(("sets", [("set:" + s, s, s in carried) for s in sets]))
        return out
    carried = [i[1:] for i in p.row() or [] if i.startswith("@")]
    origin = origins(name, p.proj, p.sk())
    out = _skill_rows(p, p.kept(), carried, lambda n: "%s  (%s)" % (n, ",".join(origin[n])) if n in origin else n)
    out.append(("sets", [("set:" + s, s, s in carried) for s in sets]))
    listed = p.proj.get("servers", [])
    out.append(("servers", [("server:" + s, s, s in listed) for s in sorted(set(p.registry()) | set(listed))]))
    out.append(("options", [("option:" + o, o, p.proj.get(o) is True) for o in OPTIONS]))
    given = p.proj.get("profiles")
    offered = given["offered"] if isinstance(given, dict) else {}
    # The rows of the offered profiles are read-only (a toggle of them is dropped, the command is the way in). The first row is the one that
    # does something: toggled, it asks a name and the questions of `forge new @NAME` once the screen is closed. It goes first so the offered
    # profiles stay the last rows.
    out.append(("profiles (open one with its command, or add one)", [(NEW_PROFILE_ROW, "new profile  (toggle it, then Enter: asks its name and its questions)", False)]
                + [("profile:" + n, "@%s  forge config %s @%s" % (n, name, n), False) for n in offered]))
    return out


def screen(name, profile, keys=None):
    """Open the key selector on project `name` (or its profile) and return the flags that turn the toggled rows round, as a list of
    (op, type, name); [] when nothing was toggled; None when the owner cancelled. `keys` is for tests (recorded key names)."""
    got = selector.run(sections(name, profile), keys=keys)
    if got is None:
        return None
    flags = []
    for row, now in got.items():
        typ, _, item = row.partition(":")
        if row == NEW_PROFILE_ROW:
            flags.append(("on", "profile", "+new"))
        elif typ != "profile":
            flags.append(("on" if now else "off", typ, item))
    return flags


def new_profile(name, prof):
    """The screen's "new profile" row: asks the profile's name, then runs `forge new @NAME` for the project (its questions, its plan, its
    confirmation) from the project's folder. The exit code of that."""
    import argparse
    from forge import new as new_cmd  # forge/new.py imports this module
    folder = prof.get("project_path", "")
    if not os.path.isdir(folder):
        _say("forge config: the folder of project %s (%s) does not exist, so forge new @NAME cannot run there" % (name, folder), err=True)
        return 2
    try:
        text = input("name of the new profile of %s: " % name).strip()
    except EOFError:
        _say(CANCELLED, err=True)
        return 0
    except KeyboardInterrupt:
        _say("forge config: interrupted (Ctrl-C), nothing was written", err=True)
        return 130
    args = argparse.Namespace(path="@" + text, parent_dir=None, stack=None, framework=False, name=None, writes_tracked_files=False, yes=False,
                              apply=False, profiles=None, sets=None, skills=None, server=None, memory=None, check=None, plugin=None, ui=False,
                              command_guard=False)
    here = os.getcwd()
    try:
        os.chdir(folder)
        return new_cmd.create_profile(args)
    finally:
        os.chdir(here)


def cmd_config(a):
    """forge config [NAME] [@PROFILE] [--on TYPE:NAME]... [--off TYPE:NAME]... [--apply | --yes] [--json]. With no flag, in a terminal,
    the key-selector screen builds the flags (exit 0 when it is cancelled or nothing was toggled); without a terminal, exit 2."""
    try:
        names = [t for t in a.targets if not t.startswith("@")]
        ats = [t for t in a.targets if t.startswith("@")]
        if len(names) > 1 or len(ats) > 1:
            raise Refusal("at most one project and one @PROFILE: %s" % " ".join(a.targets))
        changes = [parse_flag("on", t) for t in a.on or []] + [parse_flag("off", t) for t in a.off or []]
        name, prof = project_named(names[0]) if names else project_here()
        profile = None
        if ats:
            try:
                label = profiles.parse_at(ats[0])
            except ValueError as e:
                raise Refusal(str(e))
            given = prof.get("profiles")
            if not isinstance(given, dict):
                raise Refusal("project '%s' has no profiles" % name)
            known = [given["default"]] + list(given["offered"])
            if label not in known:
                raise Refusal(suggest.message("profile", "@" + label, ["@" + n for n in known], " in project '%s'" % name))
            profile = None if label == given["default"] else label  # the default is the project file as it is
        if not changes:
            if not has_terminal():
                raise Refusal("nothing to change: give --on TYPE:NAME or --off TYPE:NAME (the types are %s); `forge list %s` shows what there is" % (
                    ", ".join(TYPES), name))
            changes = screen(name, profile)
            if not changes:
                _say(NO_CHOICE if changes == [] else CANCELLED)
                return 0
            if ("on", "profile", "+new") in changes:  # the screen's own row: not a flag of change()
                changes = [c for c in changes if c[1] != "profile"]
                if changes:
                    code = change(name, profile, changes, yes=a.apply or a.yes, as_json=a.json)
                    if code:
                        return code
                return new_profile(name, prof)
    except (Refusal, profiles.ProfileError) as e:
        _say("forge config: %s" % e, err=True)
        return 2
    except Failure as e:
        _say("forge config: %s" % e, err=True)
        return 1
    return change(name, profile, changes, yes=a.apply or a.yes, as_json=a.json)
