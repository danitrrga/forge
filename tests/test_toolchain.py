def render_cases():
    want("render_mise = the golden text", toolchain.render_mise(DOC["tools"]), MISE_GOLDEN)
    want("render_pips = the golden text", toolchain.render_pips(DOC["pip"]), PIP_GOLDEN)


def check_cases(tmp):
    n = [0]

    def world(*a, **k):
        n[0] += 1
        return World(os.path.join(tmp, "w%d" % n[0]), *a, **k)

    # Present, files current: every line PASS, exit 0, not one install and not one write, with --fix too.
    w = world(DOC, ALL_TOOLS, ALL_PIP)
    code, lines = w.run("toolchain")
    want("everything present = (exit, levels)", (code, levels(lines)), (0, ALL))
    want("everything present: the summary says how many it checked", lines[-1:], ["SUMMARY: 7 passed, 0 warnings, 0 failures"])
    before = (os.stat(w.mise_file).st_mtime_ns, os.stat(w.pip_file).st_mtime_ns)
    code, lines = w.run("toolchain", "--fix")
    want("--fix over everything present = (exit, installs)", (code, w.installs()), (0, []))
    want("--fix over everything present: the files are not rewritten",
         (os.stat(w.mise_file).st_mtime_ns, os.stat(w.pip_file).st_mtime_ns), before)

    # A missing tool is a FAIL naming the pin, and without --fix nothing is installed or written.
    w = world(DOC, {"pipx:yt-dlp": "2026.8.19", "http:a-skill": "49dd158"}, {"google-api-python-client": "2.200.0"})
    code, lines = w.run("toolchain")
    want("missing = (exit, levels)", (code, levels(lines)),
         (1, dict(ALL, **{"npm:pnpm": "FAIL", "pip:PyYAML": "FAIL"})))
    want("missing: the detail names the pin", line_of(lines, "npm:pnpm").endswith("missing, pinned 10.32.1"), True)
    want("missing, no --fix: nothing installed", w.installs(), [])
    # --fix: exactly the missing ones, in one mise call and one pip call, no --upgrade; then green.
    code, lines = w.run("toolchain", "--fix")
    want("--fix = (exit, installs)", (code, w.installs()),
         (0, ["mise install npm:pnpm@10.32.1", "python3 -m pip install --disable-pip-version-check PyYAML==6.0.3"]))
    want("--fix: levels after", levels(lines), ALL)

    # Nothing present and no files: both files written as the golden text, ONE mise call, ONE pip call.
    w = world(DOC, {}, {}, files=None)
    code, lines = w.run("toolchain", "--fix")
    want("--fix over nothing = (exit, installs)", (code, w.installs()), (0, [INSTALL_ALL, PIP_ALL]))
    want("--fix over nothing: the files", (w.read(w.mise_file), w.read(w.pip_file)), (MISE_GOLDEN, PIP_GOLDEN))
    want("--fix over nothing: levels after", levels(lines), ALL)

    # Installed only at another version: still a FAIL (mise was asked for the pin), and the detail says what is there.
    w = world(DOC, dict(ALL_TOOLS, **{"npm:pnpm": ["11.0.0", "9.0.0"]}), ALL_PIP)
    code, lines = w.run("toolchain")
    want("tool at another version = (exit, level)", (code, levels(lines)["npm:pnpm"]), (1, "FAIL"))
    want("tool at another version: the detail", line_of(lines, "npm:pnpm").endswith(
        "pinned 10.32.1, installed only 11.0.0, 9.0.0"), True)

    # The pin is installed but mise resolves another version here (another config, say config.toml's `latest`,
    # requests it): a WARN, exit 0, and --fix installs nothing, because nothing is missing.
    w = world(DOC, dict(ALL_TOOLS, **{"npm:pnpm": ["10.32.1", "*11.0.0"]}), ALL_PIP)
    code, lines = w.run("toolchain", "--fix")
    want("pin installed, another version active = (exit, level, installs)", (code, levels(lines)["npm:pnpm"], w.installs()), (0, "WARN", []))
    want("pin installed, another version active: the detail", line_of(lines, "npm:pnpm").endswith(
        "pin 10.32.1 is installed, but mise resolves 11.0.0 (another config requests it); left as it is"), True)
    w = world(DOC, dict(ALL_TOOLS, **{"npm:pnpm": ["*10.32.1", "11.0.0"]}), ALL_PIP)
    code, lines = w.run("toolchain")
    want("pin installed and active = (exit, level)", (code, levels(lines)["npm:pnpm"]), (0, "PASS"))

    # A pip package at another version is a WARN, exit 0, and --fix never touches it (no upgrade, no downgrade).
    w = world(DOC, ALL_TOOLS, {"PyYAML": "7.0", "google-api-python-client": "2.200.0"})
    code, lines = w.run("toolchain")
    want("pip at another version = (exit, level)", (code, levels(lines)["pip:PyYAML"]), (0, "WARN"))
    want("pip at another version: the detail", line_of(lines, "pip:PyYAML").endswith(
        "present at 7.0, pinned 6.0.3; left as it is"), True)
    code, lines = w.run("toolchain", "--fix")
    want("--fix over a pip package at another version = (exit, installs)", (code, w.installs()), (0, []))

    # pip names are compared the way pip does: case, - _ . alike.
    w = world(DOC, ALL_TOOLS, {"pyyaml": "6.0.3", "Google_Api.Python_Client": "2.200.0"})
    code, lines = w.run("toolchain")
    want("pip names normalised = (exit, levels)", (code, sorted(levels(lines).values())), (0, ["PASS"] * 7))

    # The files. Stale and missing are FAILs that --fix rewrites with no install; a foreign file is a FAIL that
    # --fix leaves alone, byte for byte (it is somebody's own list).
    w = world(DOC, ALL_TOOLS, ALL_PIP, files="stale")
    code, lines = w.run("toolchain")
    want("stale files = (exit, levels)", (code, {k: v for k, v in levels(lines).items() if k.startswith("file:")}),
         (1, {"file:mise": "FAIL", "file:pip": "FAIL"}))
    want("stale file: the detail", "differs from config/toolchain.json" in line_of(lines, "file:mise"), True)
    code, lines = w.run("toolchain", "--fix")
    want("--fix over stale files = (exit, installs, files)", (code, w.installs(), (w.read(w.mise_file), w.read(w.pip_file))),
         (0, [], (MISE_GOLDEN, PIP_GOLDEN)))
    w = world(DOC, ALL_TOOLS, ALL_PIP, files=None)
    code, lines = w.run("toolchain")
    want("missing files = (exit, details)", (code, "missing" in line_of(lines, "file:mise") and "missing" in line_of(lines, "file:pip")), (1, True))
    w = world(DOC, ALL_TOOLS, ALL_PIP, files="foreign")
    code, lines = w.run("toolchain", "--fix")
    want("--fix over foreign files = (exit, files)", (code, (w.read(w.mise_file), w.read(w.pip_file))),
         (1, ("[tools]\n", "left-pad==1\n")))
    want("foreign file: the detail", "is not forge's" in line_of(lines, "file:mise") and "left alone" in line_of(lines, "file:pip"), True)

    # A refused write (a worktree, a copy: lib.may_write) leaves the files and still installs; the file rows
    # say so, and the reason is printed.
    w = world(DOC, {}, {}, files=None)
    code, lines = w.run("toolchain", "--fix", may_write=(False, "forge: this is a linked worktree -- nothing written"))
    want("--fix with a refused write = (exit, installs, files)", (code, w.installs(), (w.read(w.mise_file), w.read(w.pip_file))),
         (1, [INSTALL_ALL, PIP_ALL], (None, None)))
    want("--fix with a refused write: the reason is printed", "forge: this is a linked worktree -- nothing written" in lines, True)

    # A directory forge cannot write into is a `!` line naming the file, not a traceback; the other file is still
    # written and the installs still run.
    w = world(DOC, {}, {}, files=None)
    os.makedirs(w.mise_dir)
    os.chmod(w.mise_dir, 0o500)
    try:
        code, lines = w.run("toolchain", "--fix")
    finally:
        os.chmod(w.mise_dir, 0o700)
    want("an unwritable mise dir = (exit, the ! line, pip file, installs)",
         (code, any(l.startswith("! %s: " % w.mise_file) for l in lines), w.read(w.pip_file), w.installs()),
         (1, True, PIP_GOLDEN, [INSTALL_ALL, PIP_ALL]))
    # A file that cannot be read is not "somebody's own": the detail says it cannot be read, and it is left alone.
    w = world(DOC, ALL_TOOLS, ALL_PIP)
    os.remove(w.pip_file)
    os.mkdir(w.pip_file)
    code, lines = w.run("toolchain", "--fix")
    want("an unreadable file = (exit, detail)", (code, "cannot be read" in line_of(lines, "file:pip") and "not forge's" not in line_of(lines, "file:pip")), (1, True))

    # An install that exits 0 and writes nothing: the recheck is the verdict.
    w = world(DOC, {}, ALL_PIP)
    code, lines = w.run("toolchain", "--fix", FAKE_NOOP="1")
    want("an install that wrote nothing = (exit, level)", (code, levels(lines).get("npm:pnpm")), (1, "FAIL"))
    want("an install that wrote nothing: the detail", line_of(lines, "npm:pnpm").endswith(
        "missing, pinned 10.32.1; still missing after `%s`" % INSTALL_ALL), True)
    # An install that fails says why, in the line of what it was installing.
    w = world(DOC, {}, ALL_PIP)
    code, lines = w.run("toolchain", "--fix", FAKE_MISE_INSTALL_FAIL="1")
    want("a failing mise install = (exit, detail)", (code, "failed (exit 1): mise ERROR install failed" in line_of(lines, "npm:pnpm")), (1, True))

    # No mise on PATH, or a mise that cannot list: every tool FAILs with the reason, and --fix installs nothing.
    w = world(DOC, ALL_TOOLS, ALL_PIP, with_mise=False)
    code, lines = w.run("toolchain", "--fix")
    want("no mise = (exit, levels of tools, installs)", (code, [levels(lines)[k] for k in ALL_TOOLS], w.installs()),
         (1, ["FAIL"] * 3, []))
    want("no mise: the detail", "mise is not on PATH" in line_of(lines, "npm:pnpm"), True)
    w = world(DOC, ALL_TOOLS, ALL_PIP)
    code, lines = w.run("toolchain", "--fix", FAKE_MISE_LS_FAIL="1")
    want("mise ls fails = (exit, levels of tools, installs)", (code, [levels(lines)[k] for k in ALL_TOOLS], w.installs()),
         (1, ["FAIL"] * 3, []))

    # An empty list sees nothing, and seeing nothing is a FAIL (non-negotiable 7); so is no file, and a bad one.
    bad = (("empty lists", {"tools": [], "pip": []}), ("no keys", {}), ("no file", None), ("not JSON", "{tools: ["),
           ("a list", [1]), ("an entry without a version", {"tools": [{"name": "x", "why": "w"}], "pip": DOC["pip"]}),
           ("a version that is latest", {"tools": [{"name": "x", "version": "latest", "why": "w"}], "pip": DOC["pip"]}),
           ("an unknown track", {"tools": [dict(DOC["tools"][0], track="always")], "pip": DOC["pip"]}),
           ("a duplicate name", {"tools": DOC["tools"] + DOC["tools"][:1], "pip": DOC["pip"]}),
           ("an option that is not a name", {"tools": [dict(DOC["tools"][0], options={"a b": 1})], "pip": DOC["pip"]}),
           # mise reads conf.d in every directory: a file it cannot parse breaks every mise command, so what
           # cannot be written as TOML is refused before it is.
           ("an option named version", {"tools": [dict(DOC["tools"][0], options={"version": "1"})], "pip": DOC["pip"]}),
           ("an option holding an object", {"tools": [dict(DOC["tools"][0], options={"h": {"a": 1}})], "pip": DOC["pip"]}),
           ("an option holding null", {"tools": [dict(DOC["tools"][0], options={"h": None})], "pip": DOC["pip"]}),
           # A misspelled section is an error, not a section that is not there: with "pips" the pip entries
           # went unchecked and a missing PyYAML passed (round 10 of the old build).
           ("a misspelled section", {"tools": DOC["tools"], "pips": DOC["pip"]}),
           ("the old npm section", {"npm": [{"name": "pnpm", "version": "1", "why": "w"}], "tools": DOC["tools"], "pip": DOC["pip"]}))
    for label, doc in bad:
        w = world(doc, ALL_TOOLS, ALL_PIP, files=None)
        code, lines = w.run("toolchain", "--fix")
        want("%s = (exit, levels)" % label, (code, list(levels(lines).values())), (1, ["FAIL"]))
        want("%s: nothing installed or written" % label, (w.installs(), w.read(w.mise_file)), ([], None))

    # The real binary on a file of the real shape: a copy of the engine whose config/toolchain.json is the
    # fixture, and a fake machine that holds exactly what it pins.
    root = os.path.join(tmp, "engine")
    sandbox.copy_engine(root)
    sandbox.seed(root)
    with open(os.path.join(root, "config", "toolchain.json"), encoding="utf-8") as fh:
        real = json.load(fh)
    w = world(real, {e["name"]: e["version"] for e in real["tools"]}, {e["name"]: e["version"] for e in real["pip"]})
    home = os.path.join(w.base, "home")
    os.makedirs(home)  # mise is asked from HOME
    r = subprocess.run([sys.executable, os.path.join(root, "bin", "forge"), "toolchain"], capture_output=True, text=True,
                       env={**w.env(), "HOME": home, "PYTHONDONTWRITEBYTECODE": "1"})
    count = len(real["tools"]) + len(real["pip"]) + 2
    want("bin/forge toolchain over a machine that holds the pins (%s) = (exit, summary)" % " | ".join(
        l for l in r.stdout.splitlines() if l.startswith("FAIL")),
         (r.returncode, (r.stdout.splitlines() or [""])[-1], r.stderr), (0, "SUMMARY: %d passed, 0 warnings, 0 failures" % count, ""))


def row_cases(tmp):
    """The `toolchain` row of forge doctor: the check without --fix, how many it looked at, the fix named."""
    n = [0]

    def world(*a, **k):
        n[0] += 1
        return World(os.path.join(tmp, "r%d" % n[0]), *a, **k)

    fix = " -- forge toolchain --fix (writes mise's forge.toml, installs what is missing; a pip version that differs is only reported)"
    want("the row is registered", [(c, f) for n_, c, f in cli.CHECKS if n_ == "toolchain"],
         [(getattr(toolchain, "row", None), fix[4:])])

    def doctor(w, **extra):
        code, lines = w.run("doctor", only_row="toolchain", **extra)
        return code, [" ".join(l.split()) for l in lines if l[:4] in ("PASS", "WARN", "FAIL")] or [""], w.installs()

    w = world(DOC, ALL_TOOLS, ALL_PIP)
    want("row, everything present = (exit, lines, installs)", doctor(w),
         (0, ["PASS toolchain checked 3 tool(s), 2 pip package(s), 2 file(s), all present at their pin"], []))
    w = world(DOC, {"pipx:yt-dlp": "2026.8.19", "http:a-skill": "49dd158"}, {"google-api-python-client": "2.200.0"})
    want("row, missing = (exit, lines, installs): the check never fixes", doctor(w),
         (1, ["FAIL toolchain 2 failing: npm:pnpm, pip:PyYAML (checked 3 tool(s), 2 pip package(s), 2 file(s))" + fix], []))
    w = world(DOC, ALL_TOOLS, {"PyYAML": "7.0", "google-api-python-client": "2.200.0"})
    want("row, a pip version that differs = (exit, lines, installs)", doctor(w),
         (0, ["WARN toolchain 1 present at another version, left as it is: pip:PyYAML "
              "(checked 3 tool(s), 2 pip package(s), 2 file(s))" + fix], []))
    w = world(DOC, ALL_TOOLS, {"PyYAML": "7.0"}, files="stale")
    code, lines, installs = doctor(w)
    want("row, failing and differing = (exit, installs)", (code, installs), (1, []))
    want("row, failing and differing: the failing lead, the differing follow", lines[0].startswith(
        "FAIL toolchain 3 failing: pip:google-api-python-client, file:mise, file:pip (checked 3 tool(s), 2 pip package(s), "
        "2 file(s)); also at another version: pip:PyYAML"), True)
    for label, doc in (("empty lists", {"tools": [], "pip": []}), ("no file", None)):
        w = world(doc, ALL_TOOLS, ALL_PIP)
        code, lines, installs = doctor(w)
        want("row, %s = (exit, level, installs)" % label, (code, [l[:4] for l in lines], installs), (1, ["FAIL"], []))
        want("row, %s: names the fix" % label, lines[0].endswith(fix), True)
    w = world({"tools": DOC["tools"], "pips": DOC["pip"]}, ALL_TOOLS, {})
    code, lines, installs = doctor(w)
    want("row, a misspelled section = (exit, level, installs)", (code, [l[:4] for l in lines], installs), (1, ["FAIL"], []))
    # "_doc" and any other underscore key is a comment, as in the real file.
    w = world(dict(DOC, _doc="x", _why="y"), ALL_TOOLS, ALL_PIP)
    code, lines, installs = doctor(w)
    want("row, underscore keys are comments = (exit, level)", (code, [l[:4] for l in lines]), (0, ["PASS"]))
    w = world(DOC, ALL_TOOLS, ALL_PIP)
    code, lines, installs = doctor(w, FAKE_MISE_LS_FAIL="1")
    want("row, mise ls fails = (exit, level)", (code, lines[0][:4]), (1, "FAIL"))


def toy_settings(tmp):
    """On a checkout with no config/forge.json (a pure engine clone) the "no file" cases read no settings, so
    GSD reads as off and a missing config/toolchain.json is a SKIP, not the FAIL they expect. The toy file is
    the fixture's with GSD patched on, which is the machine this suite is written for; where the checkout has
    its own file it is read as before."""
    if os.path.exists(lib.SETTINGS):
        return
    with open(os.path.join(sandbox.FORGE, "tests", "fixtures", "config", "forge.json"), encoding="utf-8") as fh:
        doc = json.load(fh)
    doc["integrations"]["gsd"], doc["gsd_patches"] = True, True
    lib.SETTINGS = os.path.join(tmp, "forge.json")
    with open(lib.SETTINGS, "w", encoding="utf-8") as fh:
        json.dump(doc, fh)
    lib.settings.cache_clear()


def main():
    tmp = sandbox.mkdtemp("toolchain-test-")
    toy_settings(tmp)
    file_cases(FIXTURE, "the fixture's")
    if os.path.exists(REAL):
        file_cases(REAL, "this machine's")
    render_cases()
    check_cases(tmp)
    row_cases(tmp)
    for msg in failures:
        print("FAIL", msg)
    print("%d failure(s)" % len(failures))
    sandbox.cleanup(failures)
    sys.exit(1 if failures else 0)


if __name__ == "__main__":
    main()
