#!/usr/bin/env python3
"""config/toolchain.json and `forge toolchain` (forge/toolchain.py): forge declares every third-party tool,
mise installs it. Twice a mise update moved `latest` node and python, and the global npm and pip packages
stayed with the old versions. mise's own `npm:` and `pipx:` tools live in a
per-package directory that holds no node or python version, and `python.default_packages_file` is applied
inside `mise install python@X`, so forge now writes two files and asks mise (docs/toolchain-design.md).

Written first and run against the code that did not yet have forge/toolchain.py (the previous npm/pip
build): "ImportError: cannot import name 'toolchain' from 'forge'". Each mutation of the new module then fails
a case, all six run: pip install with --upgrade "--fix = (exit, installs) = (1, [...'python3 -m
pip install --upgrade --disable-pip-version-check PyYAML==6.0.3']), want (0, [...])"; a foreign file
overwritten "--fix over foreign files = (exit, files) = (0, ('# GENERATED by forge toolchain ...')), want (1,
('[tools]\\n', 'left-pad==1\\n'))"; the recheck replaced by the installer's word "--fix over nothing: levels
after = {... 'file:mise': 'FAIL', 'file:pip': 'FAIL'}, want {... 'PASS' ...}"; one mise call per tool "--fix
over nothing = (0, ['mise install npm:pnpm@10.32.1', 'mise install pipx:yt-dlp@2026.8.19', ...]), want (0,
[<one call>, ...])"; the options dropped from the file "render_mise = the golden text = ..."; a "latest" pin
accepted "a version that is latest = (exit, levels) = (0, ['PASS', ...]), want (1, ['FAIL'])". A second round
(the Ponytail review of the first build) added four more, each seen failing with its fix reverted: options not
validated "an option named version = (exit, levels) = (0, ['PASS', ...]), want (1, ['FAIL'])"; an active version
that differs ignored "pin installed, another version active = (exit, level, installs) = (0, 'PASS', []), want
(0, 'WARN', [])"; a write error uncaught "PermissionError: [Errno 13] Permission denied: '.../mise-config/conf.d'"
(a traceback where a `!` line belongs); an unreadable file called foreign "an unreadable file = (exit, detail)
= (1, False), want (1, True)".

1. The manifest (the fixture's and this machine's): `tools` and `pip`, entries with a name, an exact pinned
   version (never "latest": the pin is what `forge update` moves) and a why; `track` latest or frozen; a name
   once; nothing that does not build on python 3.15; `npm` itself is not a tool.
2. The two generated files, as golden text: the header, `[tools]` and one line per tool (an inline table when
   the entry has `options`), one `name==version` line per pip entry.
3. `forge toolchain` (the check; never writes, never installs), against a fake `mise` and a fake `python3` on
   PATH (see MISE_STUB): one line per tool, per pip package and per file; a missing tool, a tool installed
   only at another version, a stale, missing or foreign file are FAILs, a pip package at another version is a
   WARN; zero entries, a bad file, no mise and a mise that cannot list are FAILs (non-negotiable 7).
4. `forge toolchain --fix`: writes both files, runs ONE `mise install name@version ...` for the tools that are
   missing, ONE pip install for the missing libraries, never --upgrade, never overwrites a file that is not
   forge's, and the recheck is the verdict, not the installers' exit codes. A refused write
   (lib.may_write) leaves the files and still installs.
5. The `toolchain` row of forge doctor: the check without --fix, how many it looked at, the fix named.
"""
