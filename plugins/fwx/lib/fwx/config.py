"""The one reader of the generated .claude/fwx.json: defaults, validation, the main checkout, model and label lookups.

copied-from: forge forge/publish.py @59597b2 (main_checkout), adapted: it returns the main working tree
from anywhere (forge's returns None when already in it) and raises ConfigError outside a git repository.

Every other part reads the configuration through here and nowhere else. The file is generated by a setup tool
(forge) or written by hand to the schema in README.md; it lives in the main checkout, never in a worktree, and
a worktree finds it through git's common directory. Without the file, DEFAULTS apply and one line on stderr says so.

Imports only the standard library: `fwx statusline` has to finish in under 100 ms.
"""
import copy
import json
import os
import subprocess
import sys

SCHEMA = 1
FILE = os.path.join(".claude", "fwx.json")
ROLES = ("orchestrator", "researcher", "decisions", "state", "demo", "pre-mortem", "planner", "post-mortem",
         "executor", "reviewer", "review-verifier", "security-reviewer", "ui-walker", "ui-verifier",
         "skill-proposer", "factory-orchestrator", "intake", "classifier", "detector", "analytics-verifier",
         "vision")
SIZES = ("small", "normal", "big")
ALIASES = ("sonnet", "opus", "haiku", "fable")  # a model is one of these, never a full id


def _seed():
    """Sonnet for every role, then the seed's exceptions: the planner decides direction (Opus), the detector is
    mechanical (Haiku), the UI walker starts cheap, the analytics verifier escalates on a big job."""
    models = {r: {z: "sonnet" for z in SIZES} for r in ROLES}
    models["planner"] = {z: "opus" for z in SIZES}
    models["detector"] = {z: "haiku" for z in SIZES}
    models["ui-walker"]["small"] = "haiku"
    models["analytics-verifier"]["big"] = "opus"
    return models


DEFAULTS = {
    "schema": SCHEMA,
    "framework": True,
    "project": {"name": None, "main_checkout": None, "linear_project": None, "default_branch": None,
                "factory_branch": "factory", "checks": [], "protected_paths": [],
                "production": {"branches": [], "commands": []}, "verdict_command": None, "ui": False,
                "checks_quick": [], "app_run": None, "surface_context": {}},
    "factory": {"mode": "off", "ui_bugs": False, "watchdog_nudge_min": 30, "watchdog_fail_min": 30,
                "cost_warn_x_median": 3, "tick_trigger": None, "classifier": "suggest"},
    "weekly": {"on": True, "min_sessions": 5, "trigger": None, "precision_low": 0.7, "precision_min_marks": 20,
               "cost_target": 0.05, "improve": {}, "projects": []},
    "models": _seed(),
    "limits": {"on": True, "per_project": {}, "ram_min_free_gb": 3, "ram_per_agent_mb": 512,
               "default_cap": {"supervised": 3, "unattended": 4}},
    "rounds": 3,
    "critique_rounds_unattended": 2,
    "linear": {"labels": {}},
    "walk": {"browser_executable": None},
    "integrations": {"consent": False, "notifications": False, "agent_browser": False, "mempalace": False},
    "paths": {},
}

_warned = False  # the missing-file line is printed once per process


class ConfigError(Exception):
    """The configuration cannot be used; the message names the fix."""


def _git(cwd, *args):
    try:
        return subprocess.run(["git", "-C", cwd] + list(args), capture_output=True, text=True)
    except OSError as e:
        raise ConfigError("cannot run git (%s); fwx finds its configuration through git" % e)


def main_checkout(cwd=None):
    """The main working tree of the repository `cwd` (default: the current folder) is in, from the main tree, a
    linked worktree or any folder of either: the common git dir's `core.worktree` when set, else the parent of a
    common dir called `.git`. ConfigError outside a git repository, and for a layout git does not record (a bare
    repository, a git dir kept elsewhere)."""
    cwd = os.getcwd() if cwd is None else cwd
    r = _git(cwd, "rev-parse", "--path-format=absolute", "--git-common-dir")
    common = r.stdout.strip()
    if r.returncode or not common:
        raise ConfigError("not in a git repository: %s (run fwx inside the project's checkout)" % cwd)
    wt = _git(cwd, "config", "--file", os.path.join(common, "config"), "--get", "core.worktree")
    if wt.returncode == 0 and wt.stdout.strip():
        return os.path.abspath(os.path.join(common, wt.stdout.strip()))
    if os.path.basename(common) == ".git":
        return os.path.dirname(common)
    raise ConfigError("cannot find the main checkout: the git dir %s is not a .git folder and names no work tree" % common)


def _merge(base, over):
    """`over` laid on `base`: tables merge key by key, every other value replaces."""
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            _merge(base[k], v)
        else:
            base[k] = copy.deepcopy(v)
    return base


def _bad(path, what):
    fix = "run `forge sync`, or edit the file by hand to the schema in README.md" if path else "run `forge sync`"
    return ConfigError("%s: %s; %s" % (path or "configuration", what, fix))


def _validate(cfg, path):
    if cfg.get("schema") != SCHEMA:
        raise _bad(path, "schema is %r, this fwx reads schema %d" % (cfg.get("schema"), SCHEMA))
    models = cfg.get("models")
    if not isinstance(models, dict):
        raise _bad(path, "models is not a table of roles")
    for role, sizes in models.items():
        if role not in ROLES:
            raise _bad(path, "unknown role %r in models (roles: %s)" % (role, ", ".join(ROLES)))
        if not isinstance(sizes, dict):
            raise _bad(path, "models.%s is not a table of sizes (%s)" % (role, ", ".join(SIZES)))
        for size, name in sizes.items():
            if size not in SIZES:
                raise _bad(path, "unknown size %r for role %s (sizes: %s)" % (size, role, ", ".join(SIZES)))
            if name not in ALIASES:
                raise _bad(path, "models.%s.%s is %r, not a model alias (%s)" % (role, size, name, ", ".join(ALIASES)))


def _check_walk(cfg, path):
    """walk.browser_executable: null (the browser agent-browser finds) or the path of the browser the UI walk must use instead,
    e.g. a headless shell, so that a wrapper around the system browser (an extension, a window flag) never reaches the walk."""
    walk = cfg.get("walk")
    if not isinstance(walk, dict):
        raise _bad(path, "walk is not a table")
    exe = walk.get("browser_executable")
    if exe is not None and (not isinstance(exe, str) or not exe.strip()):
        raise _bad(path, "walk.browser_executable is %r, not null or the path of a browser" % (exe,))


def load(cwd=None):
    """The configuration: the main checkout's .claude/fwx.json laid over DEFAULTS, validated. `_source` is the
    path read, or None when the file is missing (then one line on stderr, once per process)."""
    global _warned
    main = main_checkout(cwd)
    path = os.path.join(main, FILE)
    cfg = copy.deepcopy(DEFAULTS)
    cfg["project"]["name"] = os.path.basename(main)
    cfg["project"]["main_checkout"] = main
    source = None
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except FileNotFoundError:
        if not _warned:
            _warned = True
            sys.stderr.write("fwx: no %s at %s; using defaults\n" % (FILE.replace(os.sep, "/"), path))
    except OSError as e:
        raise _bad(path, "cannot be read (%s)" % e.strerror)
    else:
        try:
            data = json.loads(text)
        except ValueError as e:
            raise _bad(path, "is not valid JSON (%s)" % e)
        if not isinstance(data, dict):
            raise _bad(path, "is not a JSON object")
        _merge(cfg, data)
        source = path
    _validate(cfg, source)
    _check_walk(cfg, source)
    cfg["_source"] = source
    return cfg


def model(cfg, role, size):
    """The model alias for `role` at `size`; ConfigError names the valid values for an unknown one."""
    if role not in ROLES:
        raise ConfigError("unknown role %r (roles: %s)" % (role, ", ".join(ROLES)))
    if size not in SIZES:
        raise ConfigError("unknown size %r (sizes: %s)" % (size, ", ".join(SIZES)))
    return cfg["models"][role][size]


def _labels(cfg):
    labels = (cfg.get("linear") or {}).get("labels", {})
    source = cfg.get("_source")
    if not isinstance(labels, dict):
        raise _bad(source, "linear.labels is not a table of neutral name to Linear name")
    for k, v in labels.items():
        if not isinstance(v, str) or not v:
            raise _bad(source, "linear.labels.%s is %r, not a label name" % (k, v))
    if len(set(labels.values())) != len(labels):
        raise _bad(source, "linear.labels sends two names to one Linear label: %s" % sorted(labels.items()))
    return labels


def label_to_linear(cfg, name):
    """The Linear name of the neutral label `name`; the same name when the mapping has no entry."""
    return _labels(cfg).get(name, name)


def label_from_linear(cfg, name):
    """The neutral name of the Linear label `name`; the same name when no neutral name maps to it."""
    return {v: k for k, v in _labels(cfg).items()}.get(name, name)
